def test_repeated_confirmation_and_reimport_change_nothing(world, client_for, db):
    admin = client_for(world.admin)
    file = _csv([["Asha Verma", "00123", "asha@example.com", "19 Nov 2026", "OPS"]])
    assert _confirm(admin, file).status_code == 200
    first_hash = _account(db, "asha@example.com").password_hash

    again = _confirm(admin, file)
    assert again.status_code == 409 and "already exists" in again.text
    # Re-importing with a corrected joining date, name and department neither updates the employee nor resets the password.
    corrected = _csv([["Asha V.", "00123", "asha@example.com", "20 Nov 2026", "CX"]])
    assert _confirm(admin, corrected).status_code == 409
    assert admin.post("/admin/employees", json=_single(employee_code="00123", work_email="asha@example.com", joining_date="2026-11-20", department_id=str(world.departments["CX"].id))).status_code == 400

    assert db.scalar(select(func.count()).select_from(Employee).where(Employee.employee_code == "00123")) == 1
    employee = db.scalar(select(Employee).where(Employee.employee_code == "00123"))
    assert (employee.full_name, employee.joining_date, employee.department_id) == ("Asha Verma", date(2026, 11, 19), world.departments["OPS"].id)
    account = _account(db, "asha@example.com")
    assert account.password_hash == first_hash and verify_password(account.password_hash, "Fin@19112026")
    assert db.scalar(select(func.count()).select_from(UserRole).where(UserRole.user_account_id == account.id)) == 1


