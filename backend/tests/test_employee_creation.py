def test_preview_resolves_departments_and_dates_and_creates_nothing(world, client_for, db):
    db.add_all([Department(code="OLD", name="Old team", is_active=False), Department(code="SALES", name="Field sales"), Department(code="FS", name="Sales")])
    db.commit()
    admin = client_for(world.admin)
    before = (_count(db, Employee), _count(db, UserAccount), _count(db, AuditLog))
    rows = [
        ["Asha Verma", "00123", "asha@example.com", "19 Nov 2026", " ops "],  # Code, any case, spaces.
        ["Rohan Iyer", "E0457", "rohan@example.com", "05/01/2026", "CX"],  # A second department in the same file.
        ["Meera Nair", "000789", "meera@example.com", "2026-11-19", "  field SALES "],  # Exact name, any case.
        ["Ishan Rao", "E9", "ishan@example.com", "19112026", ""],  # Missing department.
        ["Kavya Das", "E10", "kavya@example.com", "19-11-2026", "Marketing"],  # Unknown.
        ["Arjun Sen", "E11", "arjun@example.com", "19-11-2026", "old"],  # Inactive.
        ["Neha Jain", "E12", "neha@example.com", "19-11-2026", "Sales"],  # Code of one department, name of another.
        ["Vikram Roy", "E13", "vikram@example.com", "31/02/2026", "OPS"],  # Not a real date.
    ]
    response = _preview(admin, _csv(rows))
    assert response.status_code == 200, response.text
    data = response.json()["data"]
    assert (data["total_rows"], data["valid_rows"], data["invalid_rows"], data["ready"]) == (8, 3, 5, False)
    by_code = {r["employee_code"]: r for r in data["rows"]}
    assert by_code["00123"]["department"]["code"] == "OPS" and by_code["00123"]["joining_date"] == "2026-11-19"
    assert by_code["E0457"]["department"]["code"] == "CX" and by_code["E0457"]["joining_date"] == "2026-01-05"
    assert by_code["000789"]["department"]["code"] == "SALES"
    assert by_code["E9"]["errors"] == [{"field": "department", "message": "Required."}]
    assert "Unknown department" in by_code["E10"]["errors"][0]["message"]
    assert "inactive" in by_code["E11"]["errors"][0]["message"]
    assert "more than one active department" in by_code["E12"]["errors"][0]["message"]
    assert by_code["E13"]["errors"][0]["field"] == "joiningdate"
    assert by_code["00123"]["row"] == 2 and by_code["E13"]["row"] == 9
    # Nothing is stored by a preview: no employee, account or audit record, and no password anywhere.
    assert (_count(db, Employee), _count(db, UserAccount), _count(db, AuditLog)) == before
    assert "Fin@" not in response.text and "password" not in response.text.lower()
    assert db.scalar(select(func.count()).select_from(Department)) == 5  # No department was created.


