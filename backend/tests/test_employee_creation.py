HEADER = ["name", "employee id", "email", "joiningdate", "department"]


def _csv(rows: list[list[str]], header: list[str] = HEADER) -> bytes:
    lines = [header, *rows]
    return ("\n".join(",".join(cell for cell in line) for line in lines) + "\n").encode("utf-8")


def _preview(client, content: bytes, name: str = "people.csv"):
    return client.post("/admin/employees/import/preview", files={"file": (name, content, "text/csv")})


def _confirm(client, content: bytes, name: str = "people.csv"):
    return client.post("/admin/employees/import", files={"file": (name, content, "text/csv")})


def _account(db, email: str) -> UserAccount | None:
    db.expire_all()
    return db.scalar(select(UserAccount).where(UserAccount.login_email == email))


def _count(db, model) -> int:
    db.expire_all()
    return db.scalar(select(func.count()).select_from(model))


def _single(**overrides) -> dict:
    return {"full_name": "Asha Verma", "employee_code": "00123", "work_email": "Asha.Verma@Example.com", "joining_date": "2026-11-19", **overrides}


