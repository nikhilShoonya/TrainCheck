def test_admin_adds_one_employee_with_an_employee_account(world, client_for, db):
    admin = client_for(world.admin)
    response = admin.post("/admin/employees", json=_single(department_id=str(world.departments["CX"].id)))
    assert response.status_code == 200, response.text
    body = response.json()["data"]
    assert body["created"] == 1 and body["employee"]["employee_code"] == "00123"
    assert "password" not in response.text.lower() and "Fin@" not in response.text

    employee = db.scalar(select(Employee).where(Employee.employee_code == "00123"))
    assert employee.full_name == "Asha Verma" and employee.work_email == "asha.verma@example.com"
    assert employee.joining_date == date(2026, 11, 19) and employee.department_id == world.departments["CX"].id
    assert employee.employment_status == "ACTIVE"
    account = _account(db, "asha.verma@example.com")
    assert account.employee_id == employee.id and account.account_status == "ACTIVE"
    assert {link.role.code for link in account.role_links} == {"EMPLOYEE"}
    assert account.password_hash.startswith("$argon2") and verify_password(account.password_hash, "Fin@19112026")

    # The new employee signs in with the generated password, using any capitalisation of the email.
    assert ApiClient().login("ASHA.VERMA@example.com", "Fin@19112026").status_code == 200


