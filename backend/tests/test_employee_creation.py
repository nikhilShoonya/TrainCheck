def test_changes_between_validation_and_insert_are_caught(world, client_for, db, monkeypatch):
    """Validated again under the lock: an employee added after the first check makes the whole file wait."""
    admin = client_for(world.admin)
    real_lock = people.lock_for_create

    def someone_else_adds_rohan(session):
        real_lock(session)
        other = Employee(employee_code="E0457", full_name="Rohan elsewhere", work_email="elsewhere@example.com", department_id=world.departments["OPS"].id)
        session.add(other)
        session.flush()

    monkeypatch.setattr(people, "lock_for_create", someone_else_adds_rohan)
    rows = [["Asha Verma", "00123", "asha@example.com", "19 Nov 2026", "OPS"], ["Rohan Iyer", "E0457", "rohan@example.com", "19 Nov 2026", "CX"]]
    response = _confirm(admin, _csv(rows))
    assert response.status_code == 409 and response.json()["error"]["code"] == "IMPORT_NOT_READY"
    assert db.scalar(select(Employee).where(Employee.employee_code == "00123")) is None
    assert db.scalar(select(Employee).where(Employee.employee_code == "E0457")) is None  # Rolled back with the rest.


def test_a_failure_while_inserting_rolls_back_the_whole_file(world, client_for, db, monkeypatch):
    admin = client_for(world.admin)
    before = (_count(db, Employee), _count(db, UserAccount), _count(db, UserRole), _count(db, AuditLog))
    real_audit = people.record_audit
    calls = {"n": 0}

    def clash_on_third_row(session, *args, **kwargs):
        real_audit(session, *args, **kwargs)
        calls["n"] += 1
        if calls["n"] == 2:  # After two employees: the third row's ID appears, as if added at the same moment.
            session.add(Employee(employee_code="E3RD", full_name="Race", work_email="race@example.com"))

    monkeypatch.setattr(people, "record_audit", clash_on_third_row)
    rows = [[f"Person {i}", code, f"p{i}@example.com", "19 Nov 2026", "OPS"] for i, code in enumerate(["E1ST", "E2ND", "E3RD"], start=1)]
    response = _confirm(admin, _csv(rows))
    assert response.status_code == 409 and response.json()["error"]["code"] == "EMPLOYEE_ALREADY_EXISTS"
    assert (_count(db, Employee), _count(db, UserAccount), _count(db, UserRole), _count(db, AuditLog)) == before


